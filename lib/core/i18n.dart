  /// `{name}` placeholders are filled from [args].
  String t(String key, [Map<String, Object?> args = const {}]) {
    var s = (en ? _en[key] : null) ?? _es[key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  String status(String code) => _es.containsKey('status.$code') ? t('status.$code') : code;
  String action(String code) => _es.containsKey('action.$code') ? t('action.$code') : code;
